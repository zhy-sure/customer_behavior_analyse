
USE customer_behaviour;


-- ═══════════════════════════════════════════════════════════════
-- Q1. 男性 vs 女性客户的总收入对比
-- ═══════════════════════════════════════════════════════════════
SELECT 
    性别,
    SUM(消费金额_美元) AS 总收入,
    COUNT(客户ID)      AS 客户数,
    AVG(消费金额_美元) AS 平均消费
FROM customer
GROUP BY 性别;


-- ═══════════════════════════════════════════════════════════════
-- Q2. 哪些客户用了折扣但消费金额仍高于平均？
-- ═══════════════════════════════════════════════════════════════
SELECT 
    客户ID,
    消费金额_美元 AS 消费金额,
    商品类别      AS 品类,
    购买商品      AS 商品
FROM customer
WHERE 是否使用折扣 = '是' 
  AND 消费金额_美元 >= (SELECT AVG(消费金额_美元) FROM customer);


-- ═══════════════════════════════════════════════════════════════
-- Q3. 评分最高的 5 个商品
-- ═══════════════════════════════════════════════════════════════
SELECT 
    购买商品 AS 商品,
    ROUND(AVG(评分), 2) AS 平均评分,
    COUNT(客户ID) AS 购买人数
FROM customer
GROUP BY 购买商品
ORDER BY AVG(评分) DESC
LIMIT 5;


-- ═══════════════════════════════════════════════════════════════
-- Q4. 标准快递 vs 快递 的平均消费金额对比
-- ═══════════════════════════════════════════════════════════════
SELECT 
    配送方式,
    AVG(消费金额_美元) AS 平均消费金额,
    COUNT(客户ID)      AS 订单数
FROM customer
WHERE 配送方式 IN ('标准快递', '快递')
GROUP BY 配送方式;


-- ═══════════════════════════════════════════════════════════════
-- Q5. 订阅客户 vs 未订阅客户对比
-- ═══════════════════════════════════════════════════════════════
SELECT 
    是否订阅,
    COUNT(客户ID)       AS 客户数,
    AVG(消费金额_美元)   AS 平均消费,
    SUM(消费金额_美元)   AS 总收入,
    ROUND(AVG(评分), 2) AS 平均评分
FROM customer
GROUP BY 是否订阅
ORDER BY 总收入 DESC;


-- ═══════════════════════════════════════════════════════════════
-- Q6. 折扣使用率最高的 Top 5 商品
-- ═══════════════════════════════════════════════════════════════
SELECT 
    购买商品 AS 商品,
    ROUND(100.0 * SUM(CASE WHEN 是否使用折扣 = '是' THEN 1 ELSE 0 END) / COUNT(*), 2) AS 折扣使用率
FROM customer
GROUP BY 购买商品
ORDER BY 折扣使用率 DESC
LIMIT 5;


-- ═══════════════════════════════════════════════════════════════
-- Q7. 客户分层：新客户 / 回头客 / 忠实客户
-- ═══════════════════════════════════════════════════════════════
WITH cte AS (
    SELECT 
        CASE
            WHEN 历史购买次数 = 1 THEN '新客户'
            WHEN 历史购买次数 BETWEEN 2 AND 10 THEN '回头客'
            ELSE '忠实客户'
        END AS 客户类型
    FROM customer
)
SELECT 
    客户类型,
    COUNT(*) AS 人数,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER(), 1) AS 占比
FROM cte
GROUP BY 客户类型
ORDER BY 人数 DESC;


-- ═══════════════════════════════════════════════════════════════
-- Q8. 每个商品类别中购买量最高的 Top 3 商品
-- ═══════════════════════════════════════════════════════════════
WITH t1 AS (
    SELECT 购买商品, 商品类别, COUNT(客户ID) AS 总订单数
    FROM customer
    GROUP BY 商品类别, 购买商品
),
t2 AS (
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY 商品类别 ORDER BY 总订单数 DESC) AS 排名
    FROM t1
)
SELECT 排名, 商品类别 AS 品类, 购买商品 AS 商品, 总订单数
FROM t2
WHERE 排名 <= 3
ORDER BY 品类, 排名;


-- ═══════════════════════════════════════════════════════════════
-- Q9. 重复购买超过 5 次的客户是否更愿意订阅？
-- ═══════════════════════════════════════════════════════════════
SELECT 
    是否订阅,
    COUNT(客户ID)        AS 人数,
    AVG(历史购买次数)     AS 平均购买次数
FROM customer
WHERE 历史购买次数 > 5
GROUP BY 是否订阅;


-- ═══════════════════════════════════════════════════════════════
-- Q10. 各年龄段的收入贡献
-- ═══════════════════════════════════════════════════════════════
SELECT 
    年龄段,
    SUM(消费金额_美元)   AS 总收入,
    COUNT(客户ID)        AS 人数,
    AVG(消费金额_美元)   AS 平均消费
FROM customer
GROUP BY 年龄段
ORDER BY 总收入 DESC;
